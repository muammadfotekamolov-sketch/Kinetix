export function parseCubeLutSummary(cubeText: string): Partial<ColorGrade> {
  const lines = cubeText.split(/\r?\n/);
  let rSum = 0;
  let gSum = 0;
  let bSum = 0;
  let count = 0;
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#') || /^[A-Z_]+/.test(trimmed)) continue;
    const parts = trimmed.split(/\s+/).map(Number);
    if (parts.length === 3 && parts.every((n) => !Number.isNaN(n))) {
      rSum += parts[0];
      gSum += parts[1];
      bSum += parts[2];
      count++;
    }
  }
  if (count === 0) return { contrast: 12, saturation: 10 };
  const rAvg = rSum / count;
  const gAvg = gSum / count;
  const bAvg = bSum / count;
  const tempShift = Math.round((rAvg - bAvg) * 60);
  const tintShift = Math.round((gAvg - (rAvg + bAvg) / 2) * 50);
  return {
    temperature: Math.max(-60, Math.min(60, tempShift)),
    tint: Math.max(-60, Math.min(60, tintShift)),
    contrast: 12,
    saturation: 8,
  };
}
