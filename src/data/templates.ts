export function createClipFromMedia(params: {
  id?: string;
  track?: 'V1' | 'V2';
  type: 'video' | 'image' | 'freeze';
  src: string;
  name: string;
  startMs: number;
  durationMs: number;
}): VideoClip {
  return {
    id: params.id || `clip_${Date.now()}_${Math.random().toString(36).slice(2, 6)}`,
    track: params.track || 'V1',
    type: params.type,
    src: params.src,
    name: params.name,
    startMs: params.startMs,
    durationMs: params.durationMs,
    trimStartMs: 0,
    speed: 1,
    speedCurve: 'uniform',
    smoothSlowMo: false,
    reverse: false,
    volume: 100,
    muted: false,
    flipH: false,
    flipV: false,
    rotation: 0,
    scale: 1,
    x: 0,
    y: 0,
    crop: { top: 0, right: 0, bottom: 0, left: 0 },
    stabilize: false,
    denoise: false,
    enhance: false,
    autoReframe: false,
    bgRemove: false,
    chromaKey: { enabled: false, color: '#00ff00', tolerance: 35 },
    retouch: { smooth: 0, brighten: 0, jawline: 0, eyes: 0, bodySlim: 0 },
    transitionIn: 'none',
    transitionDurationMs: 500,
    animIn: 'none',
    animOut: 'none',
    animLoop: 'none',
    animCombo: 'none',
    mask: { type: 'none', feather: 6, invert: false, scale: 1, x: 0, y: 0 },
    blendMode: 'source-over',
    opacity: 100,
    borderWidth: 0,
    borderColor: '#00E5FF',
    shadowBlur: 0,
    color: createDefaultColorGrade(),
    keyframes: [],
  };
}

